import assert from "node:assert/strict"
import { timeOffIntervals, timeOffSchema, type TimeOffValues } from "../app/lib/team-time-off.ts"

const schema = timeOffSchema()
const base: TimeOffValues = { title: "Holiday", startDate: "2026-10-10", endDate: "2026-10-10", allDay: true, startTime: "09:00", endTime: "17:00", repeat: "none", repeatUntil: "" }
assert.equal(schema.safeParse(base).success, true)
assert.equal(schema.safeParse({ ...base, title: " " }).success, false)
assert.equal(schema.safeParse({ ...base, endDate: "2026-10-09" }).success, false)
assert.equal(schema.safeParse({ ...base, allDay: false, endTime: "08:00" }).success, false)
assert.equal(schema.safeParse({ ...base, repeat: "weekly", repeatUntil: "" }).success, true)
assert.equal(schema.safeParse({ ...base, repeat: "weekly", repeatUntil: "invalid" }).success, false)
assert.equal(schema.safeParse({ ...base, repeat: "weekly", repeatUntil: "2026-10-09" }).success, false)
assert.equal(schema.safeParse({ ...base, startDate: "", repeat: "weekly", repeatUntil: "2026-11-01" }).success, false)

const [allDay] = timeOffIntervals(base, "Europe/Helsinki")
assert.equal(allDay.startsAt.toISOString(), "2026-10-09T21:00:00.000Z")
assert.equal(allDay.endsAt.toISOString(), "2026-10-10T21:00:00.000Z")
const [dstDay] = timeOffIntervals({ ...base, startDate: "2026-10-25", endDate: "2026-10-25" }, "Europe/Helsinki")
assert.equal(+dstDay.endsAt - +dstDay.startsAt, 25 * 60 * 60 * 1000, "All-day time off includes the entire day across daylight saving changes")
const [timed] = timeOffIntervals({ ...base, allDay: false }, "Europe/Helsinki")
assert.equal(timed.startsAt.toISOString(), "2026-10-10T06:00:00.000Z")
assert.equal(timed.endsAt.toISOString(), "2026-10-10T14:00:00.000Z")
const weekly = timeOffIntervals({ ...base, allDay: false, repeat: "weekly", repeatUntil: "2026-10-31" }, "Europe/Helsinki")
assert.equal(weekly.length, 4)
assert.equal(weekly[3].startsAt.toISOString(), "2026-10-31T07:00:00.000Z", "Repeats keep local wall-clock time across daylight saving changes")
const monthly = timeOffIntervals({ ...base, startDate: "2026-01-31", endDate: "2026-01-31", repeat: "monthly", repeatUntil: "2026-03-31" }, "Europe/Helsinki")
assert.equal(monthly.length, 3)
assert.equal(monthly[1].startsAt.toISOString(), "2026-02-27T22:00:00.000Z")
assert.equal(monthly[2].startsAt.toISOString(), "2026-03-30T21:00:00.000Z", "Monthly repeats preserve the original day after short months")
const yearlyValues: TimeOffValues = { ...base, startDate: "2024-02-29", endDate: "2024-02-29", repeat: "yearly", repeatUntil: "2028-02-29" }
assert.equal(schema.safeParse(yearlyValues).success, true)
const yearly = timeOffIntervals(yearlyValues, "Europe/Helsinki")
assert.equal(yearly.length, 5)
assert.equal(yearly[1].startsAt.toISOString(), "2025-02-27T22:00:00.000Z", "Leap-day repeats use the last day of February in non-leap years")
assert.equal(yearly[4].startsAt.toISOString(), "2028-02-28T22:00:00.000Z", "Yearly repeats return to the original leap day")
const tenYears = timeOffIntervals({ ...base, repeat: "weekly", repeatUntil: "2036-10-10" }, "Europe/Helsinki")
assert.equal(tenYears.length, 522, "All weekly occurrences within ten years are saved")
assert.equal(schema.safeParse({ ...base, repeat: "yearly", repeatUntil: "" }).success, true)
assert.throws(() => timeOffIntervals({ ...base, repeat: "yearly", repeatUntil: "" }, "Europe/Helsinki"), /date range/)
const indefiniteYearly = timeOffIntervals({ ...yearlyValues, repeatUntil: "" }, "Europe/Helsinki", { from: new Date("2060-02-01"), to: new Date("2060-03-01") })
assert.equal(indefiniteYearly.length, 1, "Indefinite repeats continue well beyond the previous ten-year limit")
assert.equal(indefiniteYearly[0].startsAt.toISOString(), "2060-02-28T22:00:00.000Z")
const indefiniteMonthly = timeOffIntervals({ ...base, startDate: "2026-01-31", endDate: "2026-02-02", repeat: "monthly", repeatUntil: "" }, "UTC", { from: new Date("2040-03-01"), to: new Date("2040-03-02") })
assert.equal(indefiniteMonthly.length, 1, "An occurrence that begins before the queried range still blocks it")
assert.equal(indefiniteMonthly[0].startsAt.toISOString(), "2040-02-29T00:00:00.000Z")
assert.equal(indefiniteMonthly[0].endsAt.toISOString(), "2040-03-03T00:00:00.000Z", "Multi-day repeats preserve their calendar-day duration")
const expired = timeOffIntervals(yearlyValues, "Europe/Helsinki", { from: new Date("2060-02-01"), to: new Date("2060-03-01") })
assert.equal(expired.length, 0, "Repeats with an end date stop blocking dates after it")
console.log("Time off validation and timezone tests passed")
