import "dotenv/config"
import assert from "node:assert/strict"
import { randomUUID } from "node:crypto"
import { createServer } from "vite"

process.env.NODE_ENV = "test"
process.env.EMAIL_PROVIDER = ""
const vite = await createServer({ configFile: false, cacheDir: "node_modules/.vite-tests/booking-reschedule", appType: "custom", resolve: { alias: { "~": new URL("../app", import.meta.url).pathname } }, server: { ws: false, middlewareMode: true, hmr: false, watch: null } })
const { prisma } = await vite.ssrLoadModule("/app/lib/prisma.server.ts") as typeof import("../app/lib/prisma.server")
const { appRouter } = await vite.ssrLoadModule("/app/.server/main.ts") as typeof import("../app/.server/main")
let organizationId: string | undefined
let userId: string | undefined
try {
  const suffix = randomUUID()
  const user = await prisma.user.create({ data: { name: "Reschedule test", email: `reschedule-${suffix}@example.invalid`, emailVerified: true } })
  userId = user.id
  const organization = await prisma.organization.create({ data: { name: "Reschedule test", slug: `reschedule-${suffix}`, createdAt: new Date(), settings: { create: { timezone: "UTC", bookingTimezone: "UTC" } }, members: { create: { userId, role: "owner", createdAt: new Date() } } } })
  organizationId = organization.id
  const session = await prisma.session.create({ data: { token: randomUUID(), userId, activeOrganizationId: organizationId, expiresAt: new Date(Date.now() + 86400000) } })
  const context = { headers: new Headers(), request: undefined, prisma, user, session, organizationId, formatLocale: "en-GB", formatPreference: "eu" as const, locale: "en" as const }
  const caller = appRouter.createCaller(context)
  const anonymous = appRouter.createCaller({ ...context, user: undefined, session: undefined, organizationId: null })
  const location = await caller.location.create({ name: "Original office", slug: "original" })
  const otherLocation = await caller.location.create({ name: "Other office", slug: "other" })
  const service = await caller.service.create({ name: "Consultation", durationMinutes: 30, price: "25", locationIds: [location.id, otherLocation.id] })
  const staff = await caller.staff.create({ name: "Original team member", serviceIds: [service.id], locationIds: [location.id, otherLocation.id] })
  await caller.staff.create({ name: "Another team member", serviceIds: [service.id], locationIds: [location.id] })
  const from = new Date(Date.now() + 7 * 86400000)
  from.setUTCHours(0, 0, 0, 0)
  const to = new Date(+from + 86400000)
  const at = (hour: number, minutes = 0) => new Date(+from + (hour * 60 + minutes) * 60000)
  await caller.availability.replaceRules({ staffMemberId: staff.id, rules: [{ dayOfWeek: from.getUTCDay(), startMinute: 540, endMinute: 780, timezone: "UTC" }] })
  const booking = await anonymous.booking.create({ organizationSlug: organization.slug, serviceId: service.id, staffMemberId: staff.id, locationId: location.id, startsAt: at(10), customer: { firstName: "Test", email: "reschedule@example.invalid" } })
  const appointment = await prisma.appointment.findUniqueOrThrow({ where: { bookingCode: booking.bookingCode } })
  const management = await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })
  assert.equal(management.organization.name, organization.name)
  assert.equal(management.accentColor, null)
  const brandPage = await prisma.bookingPage.create({ data: { organizationId, slug: "branded", name: "Branded page", accentColor: "#facc15", isActive: false } })
  await prisma.organizationSettings.update({ where: { organizationId }, data: { defaultBookingPageId: brandPage.id } })
  assert.equal((await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })).accentColor, "#facc15")
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).accentColor, "#facc15")
  await prisma.organizationSettings.update({ where: { organizationId }, data: { defaultBookingPageId: null } })
  await prisma.bookingPage.delete({ where: { id: brandPage.id } })
  assert.equal(management.canCancel, true)
  assert.equal(management.canReschedule, true)
  assert.equal(management.expired, false)
  assert.equal("customer" in management.booking, false)
  assert.equal("internalNotes" in management.booking, false)
  assert.equal("settings" in management.organization, false)
  await assert.rejects(anonymous.booking.getManagementPage({ bookingCode: "invalid" }), { code: "BAD_REQUEST" })
  await assert.rejects(anonymous.booking.getManagementPage({ bookingCode: "x".repeat(32) }), { code: "NOT_FOUND" })
  const input = { bookingCode: booking.bookingCode, from, to }
  const loadSlots = () => anonymous.booking.getRescheduleSlots(input)
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, true)
  await assert.rejects(anonymous.booking.getReschedulePage({ bookingCode: "bad" }), { code: "BAD_REQUEST" })
  await assert.rejects(anonymous.booking.getRescheduleSlots({ ...input, bookingCode: "x".repeat(32) }), { code: "NOT_FOUND" })
  await assert.rejects(anonymous.booking.getRescheduleSlots({ ...input, to: new Date(+from + 32 * 86400000) }), { code: "BAD_REQUEST" })
  // A changed catalogue must not change the duration of an existing appointment
  await prisma.service.update({ where: { id: service.id }, data: { durationMinutes: 90, isActive: false } })
  let slots = (await loadSlots()).days.flatMap((day) => day.slots)
  assert.ok(slots.length > 0)
  assert.ok(slots.every((slot) => slot.staffMemberId === staff.id && slot.locationId === location.id))
  assert.ok(slots.every((slot) => +new Date(slot.endsAt) - +new Date(slot.startsAt) === 30 * 60000))
  assert.ok(!slots.some((slot) => slot.startsAt === at(10).toISOString()))
  assert.ok(slots.some((slot) => slot.startsAt === at(10, 15).toISOString()), "The original appointment is excluded from conflicts")
  const rescheduled = await anonymous.booking.reschedule({ bookingCode: booking.bookingCode, startsAt: at(10, 15) })
  assert.equal(+rescheduled.startsAt, +at(10, 15))
  assert.equal(+rescheduled.endsAt, +at(10, 45))
  assert.equal(rescheduled.bookingCode, booking.bookingCode)
  const saved = await prisma.appointment.findUniqueOrThrow({ where: { id: appointment.id } })
  assert.equal(saved.staffMemberId, staff.id)
  assert.equal(saved.locationId, location.id)
  assert.equal(await prisma.appointment.count({ where: { organizationId } }), 1)
  assert.equal(await prisma.appointmentEvent.count({ where: { appointmentId: appointment.id, type: "RESCHEDULED" } }), 1)
  // Another booking takes a slot after it has been offered
  slots = (await loadSlots()).days.flatMap((day) => day.slots)
  const candidate = slots.find((slot) => slot.startsAt === at(11, 30).toISOString())
  assert.ok(candidate)
  await prisma.service.update({ where: { id: service.id }, data: { durationMinutes: 30, isActive: true } })
  await caller.appointment.create({ serviceId: service.id, staffMemberId: staff.id, locationId: location.id, startsAt: at(11, 30), customerId: saved.customerId })
  await assert.rejects(anonymous.booking.reschedule({ bookingCode: booking.bookingCode, startsAt: at(11, 30) }), { code: "CONFLICT" })
  assert.equal(+(await prisma.appointment.findUniqueOrThrow({ where: { id: appointment.id } })).startsAt, +at(10, 15))
  assert.ok(!(await loadSlots()).days.flatMap((day) => day.slots).some((slot) => slot.startsAt === at(11, 30).toISOString()))
  await prisma.appointment.update({ where: { id: appointment.id }, data: { timezone: "Pacific/Honolulu" } })
  const localDays = (await loadSlots()).days
  const previousDay = new Date(+from - 86400000).toISOString().slice(0, 10)
  assert.ok(localDays.some((day) => day.date === previousDay && day.slots.some((slot) => slot.startsAt === at(9).toISOString())), "Days follow the appointment timezone rather than changed organization settings")
  await prisma.organizationSettings.update({ where: { organizationId }, data: { allowCustomerRescheduling: false } })
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, true, "Existing bookings retain the agreed permission")
  await prisma.appointment.update({ where: { id: appointment.id }, data: { allowCustomerRescheduling: false } })
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, false)
  await assert.rejects(loadSlots(), { code: "BAD_REQUEST" })
  await assert.rejects(anonymous.booking.reschedule({ bookingCode: booking.bookingCode, startsAt: at(9) }), { code: "BAD_REQUEST" })
  await prisma.organizationSettings.update({ where: { organizationId }, data: { allowCustomerRescheduling: true, rescheduleNoticeMinutes: 20000 } })
  await prisma.appointment.update({ where: { id: appointment.id }, data: { allowCustomerRescheduling: true, rescheduleNoticeMinutes: 20000 } })
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, false)
  await assert.rejects(loadSlots(), { code: "BAD_REQUEST" })
  await prisma.service.update({ where: { id: service.id }, data: { rescheduleNoticeMinutes: 0 } })
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, false, "Catalogue edits do not change captured notice")
  await prisma.appointment.update({ where: { id: appointment.id }, data: { rescheduleNoticeMinutes: 0 } })
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, true, "Saved appointment notice controls the deadline")
  await prisma.organizationSettings.update({ where: { organizationId }, data: { cancellationNoticeMinutes: 20000 } })
  assert.equal((await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })).canCancel, true, "Changed business notice does not rewrite existing terms")
  await prisma.appointment.update({ where: { id: appointment.id }, data: { cancellationNoticeMinutes: 20000 } })
  assert.equal((await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })).canCancel, false)
  await assert.rejects(anonymous.booking.cancel({ bookingCode: booking.bookingCode }), { code: "BAD_REQUEST" })
  await prisma.service.update({ where: { id: service.id }, data: { cancellationNoticeMinutes: 0 } })
  await prisma.appointment.update({ where: { id: appointment.id }, data: { cancellationNoticeMinutes: 0 } })
  assert.equal((await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })).canCancel, true)
  await prisma.organizationSettings.update({ where: { organizationId }, data: { allowCustomerCancellation: false } })
  assert.equal((await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })).canCancel, true)
  await prisma.appointment.update({ where: { id: appointment.id }, data: { allowCustomerCancellation: false } })
  assert.equal((await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })).canCancel, false)
  await assert.rejects(anonymous.booking.cancel({ bookingCode: booking.bookingCode }), { code: "BAD_REQUEST" })
  await prisma.organizationSettings.update({ where: { organizationId }, data: { allowCustomerCancellation: true } })
  await prisma.appointment.update({ where: { id: appointment.id }, data: { allowCustomerCancellation: true } })
  await prisma.appointment.update({ where: { id: appointment.id }, data: { status: "PENDING", expiresAt: new Date(Date.now() - 1000) } })
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, false)
  await assert.rejects(loadSlots(), { code: "BAD_REQUEST" })
  const expired = await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })
  assert.equal(expired.expired, true)
  assert.equal(expired.canCancel, false)
  assert.equal(expired.canReschedule, false)
  await prisma.appointment.update({ where: { id: appointment.id }, data: { status: "CONFIRMED", expiresAt: null } })
  await anonymous.booking.cancel({ bookingCode: booking.bookingCode })
  const cancelled = await anonymous.booking.getManagementPage({ bookingCode: booking.bookingCode })
  assert.equal(cancelled.booking.status, "CANCELLED")
  assert.equal(cancelled.canCancel, false)
  assert.equal(cancelled.canReschedule, false)
  assert.equal((await anonymous.booking.getReschedulePage({ bookingCode: booking.bookingCode })).canReschedule, false)
  await assert.rejects(loadSlots(), { code: "BAD_REQUEST" })
  console.info("PASS booking management, cancellation policies, private data isolation and token rescheduling: anonymous access, invalid links/ranges, original staff/location/duration, overlapping moves, slot conflicts, deadlines, disabled rescheduling and expired/cancelled appointments")
} finally {
  try {
    if (organizationId) {
      await prisma.appointment.deleteMany({ where: { organizationId } })
      await prisma.organization.delete({ where: { id: organizationId } })
    }
    if (userId) await prisma.user.delete({ where: { id: userId } })
  } finally {
    await prisma.$disconnect()
    await vite.close()
  }
}
